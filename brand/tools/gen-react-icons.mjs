// Builds src/components/icons.tsx from the SVG files in brand/icons/ and brand/icons/ui/.
// Run from the repo root after changing any icon:  node brand/tools/gen-react-icons.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const ROOT = new URL("../..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const SOURCES = [join(ROOT, "brand/icons"), join(ROOT, "brand/icons/ui")];
const OUT = join(ROOT, "src/components/icons.tsx");

const pascal = (name) => name.replace(/(^|-)([a-z])/g, (_, __, c) => c.toUpperCase());
const jsxAttrs = (markup) =>
  markup.replace(/\s([a-z]+)-([a-z])([a-z]*)=/g, (_, a, b, rest) => ` ${a}${b.toUpperCase()}${rest}=`);

const icons = SOURCES.flatMap((dir) =>
  readdirSync(dir)
    .filter((file) => file.endsWith(".svg"))
    .map((file) => {
      const svg = readFileSync(join(dir, file), "utf8");
      const inner = svg
        .replace(/<!--[\s\S]*?-->/g, "")
        .replace(/^[\s\S]*?<svg[^>]*>/, "")
        .replace(/<\/svg>[\s\S]*$/, "")
        .split("\n")
        .map((line) => line.trim())
        .filter(Boolean)
        .map((line) => jsxAttrs(line.replace(/\s*\/>$/, " />")));
      return { name: `${pascal(file.replace(/\.svg$/, ""))}Icon`, file: relative(ROOT, join(dir, file)).replace(/\\/g, "/"), inner };
    }),
).sort((a, b) => a.name.localeCompare(b.name));

const body = icons
  .map(
    ({ name, file, inner }) => `// ${file}
export function ${name}(props: IconProps) {
  return (
    <Icon {...props}>
${inner.map((line) => `      ${line}`).join("\n")}
    </Icon>
  );
}
`,
  )
  .join("\n");

writeFileSync(
  OUT,
  `// Generated by brand/tools/gen-react-icons.mjs from brand/icons/. Do not edit by hand.
// 24px grid, 2px stroke, currentColor. Size with a className (e.g. "size-5").
import type { SVGProps } from "react";

type IconProps = SVGProps<SVGSVGElement>;

function Icon({ children, ...props }: IconProps) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width="24"
      height="24"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...props}
    >
      {children}
    </svg>
  );
}

${body}`,
);
console.log(`Wrote ${icons.length} icons to ${OUT}`);
