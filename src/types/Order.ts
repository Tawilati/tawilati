// src/types/Order.ts

import type { OrderStatus, Prisma } from "@/app/generated/prisma/client";

// What the frontend sends for each item
export interface OrderLineInput {
  menuItemId: string;
  qty: number;
}

// The full input to the OrderService
export interface SubmitOrderInput {
  guestToken: string;       // From body (the token generated by POST /api/guest-sessions)
  idempotencyKey: string;   // From header (generated by frontend)
  items: OrderLineInput[];  // From body (the cart)
}
// src/types/Order.ts

export interface OrderResponse {
  submissionId: string;      // The idempotency record (for retries)
  orderId: string;           // The actual DiningOrder ID
  sessionId: string;         // The TableSession (bill) ID
  tableLabel: string;        // e.g., "Table 5" (for the confirmation screen)
  status: OrderStatus;       // "NEW" (just created)
  totalUSD: string;          // "25.00" (as string, since Prisma Decimal)
  totalLBP: string;          // "222500.00"
  lines: {
    menuItemId: string;
    name: string;            // e.g., "Burger"
    qty: number;
    priceUSD: string;
    priceLBP: string;
  }[];
  createdAt: Date;           // When the order was placed
}

// created: false when the Idempotency-Key was already used with the same cart (a retry).
export interface SubmitOrderResult {
  created: boolean;
  order: OrderResponse;
}

export type OrderResponseRecord = {
  submissionId: string;
  order: {
    id: string;
    sessionId: string;
    status: OrderStatus;
    totalUSD: Prisma.Decimal;
    totalLBP: Prisma.Decimal;
    createdAt: Date;
    table: {
      label: string;
    };
    orderLines: {
      menuItemId: string;
      qty: number;
      priceUSD: Prisma.Decimal;
      priceLBP: Prisma.Decimal;
      menuItem: {
        name: string;
      };
    }[];
  };
};

export function mapToOrderResponse(record: OrderResponseRecord): OrderResponse {
  return {
    submissionId: record.submissionId,
    orderId: record.order.id,
    sessionId: record.order.sessionId,
    tableLabel: record.order.table.label,
    status: record.order.status,
    totalUSD: record.order.totalUSD.toFixed(2),
    totalLBP: record.order.totalLBP.toFixed(2),
    lines: record.order.orderLines.map((line) => ({
      menuItemId: line.menuItemId,
      name: line.menuItem.name,
      qty: line.qty,
      priceUSD: line.priceUSD.toFixed(2),
      priceLBP: line.priceLBP.toFixed(2),
    })),
    createdAt: record.order.createdAt,
  };
}